/**
 * Generate the environment-aware static web contract.
 *
 * Route metadata is read from nav-registry.ts, the same authority projected by
 * page-metadata.ts at runtime. Indexability is opt-in through the reviewed
 * SiteConfig; the default is intentionally noindex with an empty sitemap.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { projectSpaRouteManifest, projectStaticRouteMetadata, readRouteRegistry } from './site-route-registry.mjs'
import { canonicalOrigin, isVersionedLocalAssetPath } from './site-assets-contract.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PUBLIC = join(ROOT, 'public')
const INDEX = join(ROOT, 'index.html')

function fail(message) {
  throw new Error(`site asset generation failed: ${message}`)
}

function envBoolean(value, name) {
  if (value === undefined || value === '') return false
  if (value !== 'true' && value !== 'false') fail(`${name} must be exactly true or false`)
  return value === 'true'
}

function xmlEscape(value) {
  return value.replace(
    /[<&>'"]/g,
    (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', "'": '&apos;', '"': '&quot;' })[character],
  )
}

function routeUrl(origin, path) {
  return `${origin}${path}`
}

function sitemapXml(origin, routes) {
  const entries = routes.map((route) => {
    const fields = [
      `    <loc>${xmlEscape(routeUrl(origin, route.path))}</loc>`,
      route.lastmod ? `    <lastmod>${route.lastmod}</lastmod>` : '',
      route.changefreq ? `    <changefreq>${route.changefreq}</changefreq>` : '',
      route.priority === undefined ? '' : `    <priority>${route.priority.toFixed(1)}</priority>`,
    ].filter(Boolean)
    return `  <url>\n${fields.join('\n')}\n  </url>`
  })
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries.join('\n')}\n</urlset>\n`
}

function robotsTxt(indexable, origin, disallowPaths) {
  const lines = ['# Generated by scripts/generate-site-assets.mjs', 'User-agent: *']
  if (!indexable) {
    lines.push('Disallow: /')
    return `${lines.join('\n')}\n`
  }
  lines.push('Allow: /')
  for (const path of disallowPaths) lines.push(`Disallow: ${path}`)
  lines.push(`Sitemap: ${origin}/sitemap.xml`)
  return `${lines.join('\n')}\n`
}

function replaceGeneratedTag(html, pattern, replacement) {
  if (!pattern.test(html)) fail(`index.html is missing generated metadata marker: ${pattern}`)
  return html.replace(pattern, replacement)
}

function renderIndex(html, indexable, origin, openGraphImagePath) {
  const rootUrl = indexable ? `${origin}/` : '/'
  const imageUrl = indexable ? `${origin}${openGraphImagePath}` : openGraphImagePath
  let output = html
  output = replaceGeneratedTag(
    output,
    /<meta name="robots"[^>]*data-site-generated="robots"[^>]*\/>/,
    `<meta name="robots" content="${indexable ? 'index,follow' : 'noindex,nofollow'}" data-site-generated="robots" />`,
  )
  output = replaceGeneratedTag(
    output,
    /<link rel="canonical"[^>]*data-site-generated="canonical"[^>]*\/>/,
    `<link rel="canonical" href="${rootUrl}" data-site-generated="canonical" />`,
  )
  output = replaceGeneratedTag(
    output,
    /<meta property="og:url"[^>]*data-site-generated="og-url"[^>]*\/>/,
    `<meta property="og:url" content="${rootUrl}" data-site-generated="og-url" />`,
  )
  output = replaceGeneratedTag(
    output,
    /<meta property="og:image"[^>]*data-site-generated="og-image"[^>]*\/>/,
    `<meta property="og:image" content="${imageUrl}" data-site-generated="og-image" />`,
  )
  output = replaceGeneratedTag(
    output,
    /<meta name="twitter:image"[^>]*data-site-generated="twitter-image"[^>]*\/>/,
    `<meta name="twitter:image" content="${imageUrl}" data-site-generated="twitter-image" />`,
  )
  return output
}

const indexable = envBoolean(
  process.env.VITE_SITE_INDEXABLE ?? process.env.VITE_INDEXABLE_ENVIRONMENT,
  'VITE_SITE_INDEXABLE',
)
let origin = null
let openGraphImagePath = '/og-image-v1.png'
if (indexable) {
  let siteConfigModule
  try {
    siteConfigModule = await import('../src/lib/site-config.ts')
  } catch (error) {
    fail(`cannot validate the runtime site config; run with Node type stripping enabled: ${error.message}`)
  }
  const siteConfig = siteConfigModule.getSiteConfig()
  if (!siteConfigModule.isIndexableSiteConfigReady(siteConfig)) {
    const validation = siteConfigModule.validateSiteConfig(siteConfig)
    fail(`site config is not release-ready for indexing: ${validation.errors.join('; ')}`)
  }
  origin = canonicalOrigin(siteConfig.canonicalOrigin)
  openGraphImagePath = siteConfig.openGraphImagePath ?? openGraphImagePath
  if (!isVersionedLocalAssetPath(openGraphImagePath)) {
    fail(`Open Graph override must be a local versioned asset path: ${openGraphImagePath}`)
  }
  try {
    await readFile(join(PUBLIC, openGraphImagePath.slice(1)))
  } catch {
    fail(`Open Graph asset is missing from public/: ${openGraphImagePath}`)
  }
}

const routeRegistry = await readRouteRegistry(ROOT)
const routeInput = projectStaticRouteMetadata(routeRegistry)
const spaRouteManifest = projectSpaRouteManifest(routeRegistry)

await writeFile(join(PUBLIC, 'robots.txt'), robotsTxt(indexable, origin ?? '', routeInput.disallowPaths))
await writeFile(
  join(PUBLIC, 'sitemap.xml'),
  sitemapXml(origin ?? 'https://invalid.invalid', indexable ? routeInput.routes : []),
)
await writeFile(join(PUBLIC, 'spa-routes.json'), `${JSON.stringify(spaRouteManifest, null, 2)}\n`)
await writeFile(INDEX, renderIndex(await readFile(INDEX, 'utf8'), indexable, origin ?? '', openGraphImagePath))
console.log(
  `site assets generated: ${indexable ? routeInput.routes.length : 0} public sitemap route(s); ${indexable ? origin : 'noindex default'}`,
)
